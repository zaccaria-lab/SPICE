def _supports_truecolor() -> bool:
    """Check whether the terminal reports 24-bit colour support."""
    return os.environ.get('COLORTERM', '').lower() in ('truecolor', '24bit')


def _rgb_to_256(r: int, g: int, b: int) -> int:
    """Nearest xterm-256 colour (6x6x6 cube or grey ramp)."""
    def cube(v: int) -> int:
        """Index (0-5) of the colour cube level (0, 95, 135, 175, 215, 255) nearest to `v`."""
        return 0 if v < 48 else 1 if v < 115 else (v - 35) // 40
    ci = 16 + 36 * cube(r) + 6 * cube(g) + cube(b)
    levels = [0, 95, 135, 175, 215, 255]
    cr, cg, cb = levels[cube(r)], levels[cube(g)], levels[cube(b)]
    grey = round(((r + g + b) / 3 - 8) / 10)
    grey = max(0, min(23, grey))
    gv = 8 + 10 * grey
    d_cube = (r - cr) ** 2 + (g - cg) ** 2 + (b - cb) ** 2
    d_grey = (r - gv) ** 2 + (g - gv) ** 2 + (b - gv) ** 2
    return 232 + grey if d_grey < d_cube else ci


def _fg(rgb: tuple[int, int, int], truecolor: bool) -> str:
    """ANSI escape code setting the text colour to `rgb`, in 24-bit colour or the nearest xterm-256 colour."""
    return '\033[38;2;{};{};{}m'.format(*rgb) if truecolor else '\033[38;5;{}m'.format(_rgb_to_256(*rgb))


def _bg(rgb: tuple[int, int, int], truecolor: bool) -> str:
    """ANSI escape code setting the background colour to `rgb`, in 24-bit colour or the nearest xterm-256 colour."""
    return '\033[48;2;{};{};{}m'.format(*rgb) if truecolor else '\033[48;5;{}m'.format(_rgb_to_256(*rgb))


def render_logo(truecolor: Optional[bool] = None) -> str:
    """SPICE logo as coloured terminal text, in 24-bit colour if `truecolor` (if None, detected from `COLORTERM`)."""
    if truecolor is None:
        truecolor = _supports_truecolor()
    rows = SPICE_LOGO.strip('\n').split('\n')
    reset = '\033[0m'
    out = []
    for top, bottom in zip(rows[0::2], rows[1::2]):
        line = []
        prev = None
        for t, b in zip(top, bottom):
            tc, bc = SPICE_PALETTE.get(t), SPICE_PALETTE.get(b)
            if (tc is not None) and (bc is not None):
                code, ch = _fg(tc, truecolor) + _bg(bc, truecolor), '\u2580'   # ▀
            elif tc:
                code, ch = reset + _fg(tc, truecolor), '\u2580'
            elif bc:
                code, ch = reset + _fg(bc, truecolor), '\u2584'                # ▄
            else:
                code, ch = reset, ' '
            if code != prev:
                line.append(code)
                prev = code
            line.append(ch)
        out.append(''.join(line).rstrip() + reset)
    return '\n'.join(out) + '\n'
